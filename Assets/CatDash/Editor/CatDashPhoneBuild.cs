using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace CatDash.EditorTools
{
    /// <summary>
    /// Builds a sideloadable Android APK from the code-generated CatDash scene, for phone QA only.
    /// Owner: CI/Captain. Never invoked by tests, never touches the AAB/Play path (that stays in
    /// <c>UnityAgentKit.Editor.KitBuild.BuildAndroid</c>).
    /// </summary>
    /// <remarks>
    /// Why this exists: game-ci's default build script reads <c>EditorBuildSettings.scenes</c>, and this repo
    /// keeps no EditorBuildSettings asset in git (the scene is generated by CatDashSceneGenerator, whose build
    /// settings entry lives in Library/, which is gitignored). With no scenes Unity fails with
    /// "Cannot build untitled scene" (exit 103). Passing the scene path explicitly removes that dependency.
    /// Signing is left to Unity's own debug keystore (PlayerSettings.Android.useCustomKeystore stays false), so
    /// no ANDROID_KEYSTORE_* secret is required for a preview build; a release AAB still goes through the kit.
    /// </remarks>
    public static class CatDashPhoneBuild
    {
        private const string ScenePath = CatDashSceneGenerator.ScenePath;
        private const string OutputPath = "build/apk/android/Game.apk";
        private const string KitConfigPath = "unity-kit.json";

        [Serializable]
        private class KitConfig
        {
            public string packageName;
            public string productName;
            public string versionName;
        }

        /// <summary>Entry point used by the `apk` job in .github/workflows/unity-android.yml.</summary>
        public static void BuildPhoneApk()
        {
            EditorSettings.serializationMode = SerializationMode.ForceText;
            if (!File.Exists(ScenePath))
                throw new Exception($"CatDashPhoneBuild: {ScenePath} is not committed; run the scene job first.");

            var config = File.Exists(KitConfigPath)
                ? JsonUtility.FromJson<KitConfig>(File.ReadAllText(KitConfigPath))
                : null;
            if (config == null || string.IsNullOrWhiteSpace(config.packageName))
                throw new Exception($"CatDashPhoneBuild: {KitConfigPath} must define a real packageName.");
            if (config.packageName.StartsWith("com.example.", StringComparison.Ordinal))
                throw new Exception("CatDashPhoneBuild: replace the placeholder packageName in " + KitConfigPath + ".");

            PlayerSettings.SetApplicationIdentifier(NamedBuildTarget.Android, config.packageName);
            PlayerSettings.productName = config.productName;
            PlayerSettings.bundleVersion = string.IsNullOrEmpty(config.versionName) ? "0.1.0" : config.versionName;
            PlayerSettings.Android.bundleVersionCode = 1;
            PlayerSettings.Android.minSdkVersion = AndroidSdkVersions.AndroidApiLevel26;
            PlayerSettings.Android.targetArchitectures = AndroidArchitecture.ARM64;
            EditorUserBuildSettings.buildAppBundle = false;
            EditorUserBuildSettings.androidCreateSymbols = AndroidCreateSymbols.Disabled;

            var options = new BuildPlayerOptions
            {
                scenes = new[] { ScenePath },
                locationPathName = OutputPath,
                target = BuildTarget.Android,
                options = BuildOptions.None
            };
            var report = BuildPipeline.BuildPlayer(options);
            if (report.summary.result != BuildResult.Succeeded)
                throw new Exception("CatDashPhoneBuild: build failed: " + report.summary.result);
            if (!File.Exists(OutputPath))
                throw new Exception("CatDashPhoneBuild: Unity reported success but " + OutputPath + " is missing.");
            Debug.Log($"CatDashPhoneBuild: wrote {OutputPath} ({new FileInfo(OutputPath).Length} bytes) for {config.packageName}; sideload QA only.");
        }
    }
}
